/// ERC-721 and ERC-1155 fixtures for local-node tests. Both mocks mint
/// without restriction; `tokenURI` returns a `data:` JSON URI and `uri` an
/// `{id}` template. Source: `TestVectors/MockNFTs.sol` (solc 0.8.35).
extension EthereumNode {
    /// Deploys the mock ERC-721 and returns its address.
    public func deployMockERC721(signer: EthereumPKeySigner) async throws -> EthereumAddress {
        try await deploy(Self.mockERC721CreationBytecode, signer: signer, name: "ERC-721")
    }

    /// Deploys the mock ERC-1155 and returns its address.
    public func deployMockERC1155(signer: EthereumPKeySigner) async throws -> EthereumAddress {
        try await deploy(Self.mockERC1155CreationBytecode, signer: signer, name: "ERC-1155")
    }

    /// Mints ERC-721 `id` to `recipient` and waits for the receipt.
    public func mintERC721(
        signer: EthereumPKeySigner,
        contract: EthereumAddress,
        recipient: EthereumAddress,
        id: BigUInt
    ) async throws {
        let hash = try await send(
            signer: signer,
            to: contract,
            data: EthereumABI.encodeCall(
                selector: EthereumABI.selector("mint(address,uint256)"),
                parameters: [.address(recipient), .uint256(id)]
            ),
            gasLimit: 200_000
        )

        _ = try await waitForReceipt(hash)
    }

    /// Mints `amount` of ERC-1155 `id` to `recipient` and waits for the receipt.
    public func mintERC1155(
        signer: EthereumPKeySigner,
        contract: EthereumAddress,
        recipient: EthereumAddress,
        id: BigUInt,
        amount: BigUInt
    ) async throws {
        let hash = try await send(
            signer: signer,
            to: contract,
            data: EthereumABI.encodeCall(
                selector: EthereumABI.selector("mint(address,uint256,uint256)"),
                parameters: [.address(recipient), .uint256(id), .uint256(amount)]
            ),
            gasLimit: 200_000
        )

        _ = try await waitForReceipt(hash)
    }

    private func deploy(_ bytecode: Data, signer: EthereumPKeySigner, name: String) async throws -> EthereumAddress {
        let hash = try await send(signer: signer, to: nil, data: bytecode, gasLimit: 2_000_000)

        guard let address = try await waitForReceipt(hash).contractAddress else {
            throw EthereumLaunchError(description: "mock \(name) deployment produced no contract address")
        }

        return try EthereumAddress(string: address)
    }

    private static func bytes(_ hex: String) -> Data {
        Data(stride(from: 0, to: hex.count, by: 2).map { offset in
            let start = hex.index(hex.startIndex, offsetBy: offset)
            return UInt8(hex[start ..< hex.index(start, offsetBy: 2)], radix: 16) ?? 0
        })
    }

